'use strict';
const assert=require('node:assert/strict');
const {cpu,timeline}=require('./issue_sampling_aggregate.cjs');
const url='http://127.0.0.1:4321/issue-history.js';
const frame=(id,functionName,url='')=>({id,callFrame:{functionName,url}});
const profile={startTime:1000,endTime:21000,nodes:[frame(1,'render',url),frame(2,'(idle)'),frame(3,'(program)'),frame(4,'(garbage collector)'),frame(5,'pretend','https://untrusted.example/issue-history.js'),frame(6,'(anonymous)')],samples:[1,2,3,4,5,99,6],timeDeltas:[1000,2000,3000,4000,1000,2000,3000]};
const result=cpu(profile,[url]);
assert.equal(result.samples,7);
assert.equal(result.weighted_interval_ms,16);
assert.equal(result.profile_elapsed_ms,20);
assert.equal(result.unrepresented_tail_ms,4,'unsampled end tail must remain explicit');
const bucket=name=>result.rows.filter(row=>row.bucket===name).reduce((sum,row)=>sum+row.weighted_interval_ms,0);
assert.equal(bucket('known_script'),1,'only exact allowlisted script identity may be named');
assert.equal(bucket('idle'),2);
assert.equal(bucket('program'),3);
assert.equal(bucket('garbage collector'),4);
assert.equal(bucket('unattributed'),6,'foreign URL, missing ID and anonymous native frame remain unattributed');
assert.equal(result.rows.find(row=>row.bucket==='known_script').function,'render');
assert.equal(result.rows.reduce((sum,row)=>sum+row.weighted_interval_ms,0),16);
const invalid=changes=>assert.throws(()=>cpu({...profile,...changes},[url]));
invalid({timeDeltas:[1]});
invalid({timeDeltas:[-1,2,3,4,5,6,7]});
invalid({timeDeltas:[NaN,2,3,4,5,6,7]});
invalid({endTime:999});
invalid({startTime:NaN});
invalid({endTime:Infinity});
invalid({timeDeltas:[30000,2,3,4,5,6,7]});
const event=(name,ts,dur,extra={})=>({name,ts,dur,pid:1,tid:2,ph:'X',...extra});
const events=[{name:'begin',ts:1000,pid:1,tid:2},{name:'end',ts:11000,pid:1,tid:2},event('Layout',0,4000),event('Layout',3000,5000),event('Layout',9000,5000),event('Layout',0,20000,{pid:9}),event('Layout',0,20000,{tid:9}),event('Layout',0,20000,{ph:'B'}),event('Layout',2000,-100),event('Layout',NaN,100),event('Paint',4000,4000)];
const traced=timeline(events,'begin','end');
assert.equal(traced.window_ms,10);
assert.equal(traced.events.Layout.count,3);
assert.equal(traced.events.Layout.union_ms,9,'overlap is united and both edges clipped on marker thread');
assert.equal(traced.events.Layout.max_clipped_ms,5);
assert.equal(traced.events.Paint.union_ms,4,'nested other category remains independent');
assert.equal(traced.events.RunTask.count,0);
assert.equal(traced.events.RunTask.union_ms,0);
assert.throws(()=>timeline([{name:'begin',ts:5,pid:1,tid:2},{name:'end',ts:4,pid:1,tid:2}],'begin','end'));
assert.throws(()=>timeline([{name:'begin',ts:1,pid:1,tid:2},{name:'end',ts:4,pid:1,tid:3}],'begin','end'));
console.log('PASS CPU weighted-interval attribution, explicit tail, strict script identity and clipped trace unions');
const {captureCpu}=require('./issue_sampling_aggregate.cjs');
const accepted=captureCpu(profile,[url]);
assert.equal(accepted.status,'usable_capture');
assert.deepEqual(Object.fromEntries(Object.entries(accepted).filter(([key])=>key!=='status')),result);
for(const changes of [{timeDeltas:[1000,-2000,3000,4000,1000,2000,3000]},{timeDeltas:[1000,NaN,3000,4000,1000,2000,3000]},{timeDeltas:[1000]},{endTime:0}]){
 const input={...profile,...changes};
 const before=structuredClone(input);
 const rejected=captureCpu(input,[url]);
 assert.equal(rejected.status,'unusable_capture');
 for(const key of ['rows','weighted_interval_ms','profile_elapsed_ms','unrepresented_tail_ms'])assert.equal(rejected[key],null,'invalid capture must not expose quantified '+key);
 assert.ok(rejected.reason.length<=240);
 assert.deepEqual(input,before,'failed capture never repairs input');
 assert.equal(JSON.stringify(rejected).includes('untrusted.example'),false,'failure diagnostics contain no captured script URLs');
}
const negative=captureCpu({...profile,timeDeltas:[1000,-2000,3000,4000,1000,2000,3000]},[url]);
assert.equal(negative.diagnostics.negative_interval_count,1);
assert.equal(negative.diagnostics.minimum_negative_interval_us,-2000);
assert.equal(negative.diagnostics.sample_count,7);
assert.equal(captureCpu({...profile,timeDeltas:[NaN]},[url]).diagnostics.has_nonfinite_interval,true);
console.log('PASS unusable CPU captures remain null, unrepaired and distinct from functional parity');
